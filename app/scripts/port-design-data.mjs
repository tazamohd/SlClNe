// Ports the design bundle's data layer into typed TS modules.
//
// The prototypes keep every table, the Arabic dictionary and the RBAC matrix in
// one 668-line `gms-data.js`. That file is the handoff's declared source of
// truth (README §9), so rather than retyping ~2000 Arabic keys by hand we
// import it and emit TS. Re-run this whenever the design bundle is refreshed:
//
//   node scripts/port-design-data.mjs
//
// Hand-written files (types.ts, rbac.ts, the repository layer) are never
// touched by this script.
import { writeFileSync, mkdirSync, readFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const designDir = resolve(here, '../../project')
const outDir = resolve(here, '../src/data/generated')
mkdirSync(outDir, { recursive: true })

const D = await import(pathToFileURL(resolve(designDir, 'gms-data.js')).href)

const BANNER = `// GENERATED by scripts/port-design-data.mjs — do not edit by hand.
// Source: project/gms-data.js (the design bundle's source of truth).
`

const lit = (v) => JSON.stringify(v, null, 2)

function emit(file, body) {
  writeFileSync(resolve(outDir, file), BANNER + body)
  console.log('  wrote', file)
}

