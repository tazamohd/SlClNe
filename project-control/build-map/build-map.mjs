/** Renders the SALIS AUTO Build Map from its template plus the generated
 *  control-plane data.
 *
 *      node project-control/build-map/build-map.mjs
 *
 *  Run after `npm run registry` (app/) so the page reads the current registry,
 *  and after `npm run golden` so the golden-path panel reads the current run.
 *  The deck is built the same way — see project-control/tracker/build-deck.mjs.
 *
 *  Why this file exists: the build map was hand-written as a 21 Aug 2026
 *  snapshot and eleven of its twelve headline numbers went stale. The page
 *  itself says a hardcoded count is a defect, so every figure it prints is now
 *  substituted here from a file something else generated.
 *
 *  The ONE exception is remaining effort. Nothing in the repository computes
 *  engineer-days, so those figures live in estimates.json — declared, dated,
 *  and labelled as an estimate on the page beside its date. See that file.
 *
 *  Idempotence: no wall-clock date is read anywhere in this script. Every date
 *  the page prints is the `generatedAt` of the file it came from, so a second
 *  run with unchanged inputs produces byte-identical output. write() still
 *  compares before writing (the same guard app/scripts/build-registry.mjs
 *  uses) so a no-op run touches nothing on disk.
 */
