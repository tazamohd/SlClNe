// ── render ───────────────────────────────────────────────────────────────────

const templatePath = path.join(here, 'template.html')
let html = fs.readFileSync(templatePath, 'utf8')
/** Longest token first, so __GP_TOTAL__ can never be eaten by a shorter prefix. */
for (const key of Object.keys(TOKENS).sort((a, b) => b.length - a.length)) {
  if (!html.includes(key)) throw new Error(`template is missing ${key}`)
  html = html.split(key).join(String(TOKENS[key]))
}
/** The whole point of the exercise: nothing may reach the page unsubstituted,
 *  and a token left in the template because the generator forgot to define it
 *  is exactly the hardcoded-count defect wearing a disguise. */
const leftover = html.match(/__[A-Z0-9_]+__/g)
if (leftover) throw new Error(`unsubstituted tokens: ${[...new Set(leftover)].join(', ')}`)

/** Writes only when the content actually differs — the same guard
 *  app/scripts/build-registry.mjs uses, minus its stamp mask, which this page
 *  does not need because it prints no wall-clock date. `\r\n` is normalised so
 *  a CRLF checkout does not look like a change. */
const normalise = (t) => t.replace(/\r\n/g, '\n')
const out = path.join(here, 'build-map.html')
const changed = !fs.existsSync(out) || normalise(fs.readFileSync(out, 'utf8')) !== normalise(html)
if (changed) fs.writeFileSync(out, html)
console.log(`build map: ${(html.length / 1024).toFixed(0)} kB · ${Object.keys(TOKENS).length} tokens · ` +
  `${changed ? 'written' : 'unchanged'} → ${path.relative(REPO, out)}`)
console.log(`  registry ${REG.generatedAt} · golden ${GOLDEN.generatedAt.slice(0, 10)} · ` +
  `gates ${GATES.generatedAt.slice(0, 10)} · estimate ${EST.estimatedAt} (human)`)
