/** The three provenance figures — how many designs, how many spec screens, and
 *  how many names appear in both — are not in MASTER_REGISTRY.json: the
 *  registry stores the *union*, so the overlap it reconciled away is gone by
 *  the time it is written. They are read instead from the generated data the
 *  registry itself reads (`// GENERATED by scripts/port-design-data.mjs — do
 *  not edit by hand`), which is still a measurement rather than a
 *  transcription. Same for the RBAC matrix's shape and the fixture tables.
 *  Parsing mirrors build-registry.mjs's `literal`: these files are a JSON
 *  literal after the `= `, so this is exact rather than a regex guess. */
const readApp = (rel) => fs.readFileSync(path.join(APP, rel), 'utf8')
const literal = (rel) => {
  const s = readApp(rel)
  const i = s.indexOf('= [') >= 0 ? s.indexOf('= [') : s.indexOf('= {')
  const open = s[i + 2]
  const close = open === '[' ? s.lastIndexOf(']') : s.lastIndexOf('}')
  return JSON.parse(s.slice(i + 2, close + 1))
}
const pickObject = (src, name) => {
  const start = src.indexOf(`export const ${name}`)
  const brace = src.indexOf('{', start)
  let depth = 0
  for (let i = brace; i < src.length; i++) {
    if (src[i] === '{') depth++
    else if (src[i] === '}' && --depth === 0) return JSON.parse(src.slice(brace, i + 1))
  }
  throw new Error(`could not read ${name}`)
}

